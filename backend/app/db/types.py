"""数据库类型抽象：屏蔽 PostgreSQL 与 SQLite 的类型差异

核心问题：
    PostgreSQL 用 BIGINT GENERATED ALWAYS AS IDENTITY 自增主键
    SQLite 只认 INTEGER PRIMARY KEY 自增（BIGINT 不行）

解决方案：BigInteger().with_variant(Integer, "sqlite")
    → PG 上生成 BIGINT + Identity
    → SQLite 上生成 INTEGER PRIMARY KEY（自增）

用法：
    from app.db.types import pk_column, fk_column, json_column

    class MyModel(Base):
        id: Mapped[int] = pk_column()
        user_id: Mapped[int] = fk_column("sys_user.id")
        extra: Mapped[dict | None] = json_column(nullable=True)
"""
from __future__ import annotations

from typing import Any

from sqlalchemy import BigInteger, DateTime, Integer, Numeric, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column


# ================================================================ 主键
# PG: BIGINT GENERATED BY DEFAULT AS IDENTITY
# SQLite: INTEGER PRIMARY KEY（自增）
BIGINT_PK = BigInteger().with_variant(Integer, "sqlite")


def pk_column(comment: str | None = None) -> Any:
    """自增主键列

    注意：用 autoincrement=True 而非 Identity(always=True)，
    因为 SQLite 不支持 Identity，且 autoincrement 在 PG 上也会生成 IDENTITY。
    """
    return mapped_column(
        BIGINT_PK,
        primary_key=True,
        autoincrement=True,
        comment=comment,
    )


# ================================================================ 外键
def fk_column(
    target: str,
    *,
    nullable: bool = True,
    comment: str | None = None,
    index: bool = False,
) -> Any:
    """外键列（同样需要 SQLite 的 INTEGER 变体）"""
    from sqlalchemy import ForeignKey

    return mapped_column(
        BIGINT_PK,
        ForeignKey(target),
        nullable=nullable,
        index=index,
        comment=comment,
    )


def bigint_column(
    *,
    nullable: bool = True,
    comment: str | None = None,
    index: bool = False,
) -> Any:
    """普通 BIGINT 列（非主键非外键）"""
    return mapped_column(
        BIGINT_PK,
        nullable=nullable,
        index=index,
        comment=comment,
    )


# ================================================================ JSON
# PG: JSONB（可索引、支持 -> 操作符）
# SQLite: JSON（实际存 TEXT，SQLAlchemy 自动序列化/反序列化）
JSON_TYPE = JSONB().with_variant(
    __import__("sqlalchemy").JSON, "sqlite"
)


def json_column(
    *,
    nullable: bool = True,
    default: Any = None,
    comment: str | None = None,
) -> Any:
    """JSON 列

    PG 上用 JSONB（保留完整能力），SQLite 上降级为 JSON（存 TEXT）。
    业务代码用 dict 读写，两种数据库表现一致。
    """
    kwargs: dict[str, Any] = {"nullable": nullable, "comment": comment}
    if default is not None:
        kwargs["default"] = default
    return mapped_column(JSON_TYPE, **kwargs)


# ================================================================ 其他常用类型
def string_column(
    length: int,
    *,
    nullable: bool = False,
    default: str | None = None,
    server_default: str | None = None,
    comment: str | None = None,
    unique: bool = False,
    index: bool = False,
) -> Any:
    kwargs: dict[str, Any] = {
        "nullable": nullable,
        "comment": comment,
        "unique": unique,
        "index": index,
    }
    if default is not None:
        kwargs["default"] = default
    if server_default is not None:
        kwargs["server_default"] = server_default
    return mapped_column(String(length), **kwargs)


def text_column(*, nullable: bool = True, comment: str | None = None) -> Any:
    return mapped_column(Text, nullable=nullable, comment=comment)


def int_column(
    *,
    nullable: bool = False,
    default: int | None = None,
    server_default: str | None = None,
    comment: str | None = None,
) -> Any:
    kwargs: dict[str, Any] = {"nullable": nullable, "comment": comment}
    if default is not None:
        kwargs["default"] = default
    if server_default is not None:
        kwargs["server_default"] = server_default
    return mapped_column(Integer, **kwargs)


def numeric_column(
    precision: int = 14,
    scale: int = 2,
    *,
    nullable: bool = True,
    comment: str | None = None,
) -> Any:
    return mapped_column(Numeric(precision, scale), nullable=nullable, comment=comment)


def timestamptz_column(
    *,
    nullable: bool = False,
    server_default_now: bool = False,
    onupdate_now: bool = False,
    comment: str | None = None,
) -> Any:
    """时间戳列

    PG: TIMESTAMP WITH TIME ZONE
    SQLite: DATETIME（存字符串，SQLAlchemy 自动转换）
    """
    kwargs: dict[str, Any] = {"nullable": nullable, "comment": comment}
    if server_default_now:
        kwargs["server_default"] = func.now()
    if onupdate_now:
        kwargs["onupdate"] = func.now()
    return mapped_column(DateTime(timezone=True), **kwargs)


def date_column(*, nullable: bool = True, comment: str | None = None) -> Any:
    from sqlalchemy import Date

    return mapped_column(Date, nullable=nullable, comment=comment)


def bool_column(
    *,
    nullable: bool = False,
    default: bool = False,
    server_default: str | None = None,
    comment: str | None = None,
) -> Any:
    from sqlalchemy import Boolean

    kwargs: dict[str, Any] = {"nullable": nullable, "default": default, "comment": comment}
    if server_default is not None:
        kwargs["server_default"] = server_default
    return mapped_column(Boolean, **kwargs)


# ================================================================ 时区感知时间戳
from sqlalchemy import DateTime as _DateTime
from sqlalchemy.types import TypeDecorator


class AwareDateTime(TypeDecorator):
    """时区感知的 DateTime

    问题：SQLite 不存时区，读出来是 naive datetime，
         与 datetime.now(UTC) 相减会报
         "can't subtract offset-naive and offset-aware datetimes"。

    解决：读写时统一按 UTC 处理：
         - 写入：naive 视为 UTC，aware 转 UTC
         - 读取：始终附加 UTC 时区
    """

    impl = _DateTime(timezone=True)
    cache_ok = True

    def process_bind_param(self, value, dialect):
        if value is None:
            return None
        if value.tzinfo is None:
            # naive 视为 UTC
            from datetime import UTC

            return value.replace(tzinfo=UTC)
        return value

    def process_result_value(self, value, dialect):
        if value is None:
            return None
        if value.tzinfo is None:
            from datetime import UTC

            return value.replace(tzinfo=UTC)
        return value


def aware_timestamp(
    *,
    nullable: bool = False,
    server_default: Any = None,
    onupdate: Any = None,
    default: Any = None,
    comment: str | None = None,
    **extra: Any,
) -> Any:
    """时区感知时间戳列（双库一致）

    支持与原 mapped_column 相同的参数，并额外提供：
        server_default_now=True  等价于 server_default=func.now()
        onupdate_now=True        等价于 onupdate=func.now()
    """
    kwargs: dict[str, Any] = {"nullable": nullable, "comment": comment}

    if extra.pop("server_default_now", False) and server_default is None:
        server_default = func.now()
    if extra.pop("onupdate_now", False) and onupdate is None:
        onupdate = func.now()

    if server_default is not None:
        kwargs["server_default"] = server_default
    if onupdate is not None:
        kwargs["onupdate"] = onupdate
    if default is not None:
        kwargs["default"] = default

    kwargs.update(extra)
    return mapped_column(AwareDateTime, **kwargs)
